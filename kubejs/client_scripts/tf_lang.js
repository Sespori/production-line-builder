// 为什么不用 kubejs/assets/kubejs/lang/*.json：
//   KubeJS 在注册物品时会为每个物品自动生成一条 translationKey -> 注册路径
//   （即 item.kubejs.dust_mithril = "dust_mithril"），写进它自己的虚拟资源包。
//   KubeJS 的虚拟包在资源包列表里优先级最高，会盖掉 kubejs/assets 下的同名 json，
//   所以之前放在 assets 里的译名全部没生效，游戏内显示的是路径名。
//   ClientEvents.lang 在 KubeJS 生成默认 lang 之后执行，能正确覆盖，
//   并且可以按语言分别设置，中文/英文都能显示正确。
// 生效：/reload 即可（lang 属于客户端资源，不需要重启）

